    <div>
      <h2>Bring a little green indoors</h2>
      <p>When the weather turns and the beds are put to rest, a few houseplants keep a gardener's hands busy and a room full of life. Our <a href="plant-care.html">Plant Care</a> guide ends with a friendly section on easy, forgiving houseplants — the pothos, the snake plant, the spider plant — that thrive on a little benign neglect and ask almost nothing in return.</p>
    </div>
  </div>


  <h1>Welcome to Hollyhock Lane</h1>
  <p class="hero__lead">A friendly journal of cottage gardening and gentle home keeping — plain-spoken guides to growing flowers and vegetables, caring for a lawn, and tending the small repairs that keep a home snug, all at an unhurried pace.</p>

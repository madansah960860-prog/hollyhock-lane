      <h2>Grow a garden you love</h2>
      <p>A cottage garden is a generous, forgiving thing. It does not ask for perfection or expensive tools — only a little attention, a willingness to learn as you go, and the patience to let things grow in their own time. Our <a href="plant-care.html">Plant Care</a> guide covers the gentle fundamentals: how to water well, read your soil, place a plant in the right light, and prune without fear.</p>
      <p>Whether you tend a sweep of borders or a few pots by the door, the basics are the same, and they are kinder and simpler than you might think.</p>
    </div>
  </div>


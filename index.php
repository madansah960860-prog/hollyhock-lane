    <div>
      <h2>Keep a healthy lawn</h2>
      <p>A good lawn is less about hard work than about a few sensible habits — mowing high, watering deeply but seldom, and feeding the soil rather than fighting it. Our <a href="lawn-care.html">Lawn Care</a> guide walks through the seasonal rhythm, from spring's first cut to autumn's overseeding, with gentle, low-water options for those who would rather not fuss.</p>
    </div>
  </div>

